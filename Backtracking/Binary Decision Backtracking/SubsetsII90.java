    static void solve1(int current, int[] nums, List<List<Integer>> subsets, List<Integer> ans){
        if(current == nums.length){
            subsets.add(new ArrayList<>(ans));
            return;

        }

        ans.add(nums[current]);
        solve1(current+1, nums, subsets, ans);
        ans.remove(ans.size()-1);

        //for skip remove all duplicates

        int next = current +1;
        while(next<nums.length && nums[next] == nums[next-1]){
            next++;
        }

        solve1(next, nums, subsets, ans);
    
    }

    static int countSubsets(int current, int nums[]){
        if(current == nums.length){
            return 1;
        }

        int take = countSubsets(current + 1, nums);
        int next = current+1;
        while(next<nums.length && nums[next] == nums[next-1]){
            next++;
        }
        int skip = countSubsets(next, nums);
        return take + skip;
    }
